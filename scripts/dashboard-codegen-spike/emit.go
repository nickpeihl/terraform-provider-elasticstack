package main

import (
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// Strategies for a field the OpenAPI document marks with a `default`.
const (
	// strategyComputed: Optional + Computed with the default as the schema's Default. The plan holds
	// the value Kibana will store, so the read maps the API as it is and needs no prior state.
	strategyComputed = "computed"
	// strategyPreserve: keep Optional (the released schema). The read takes the prior state and
	// applies one generic rule: an unset field that comes back as its default reads as null.
	strategyPreserve = "preserve"
)

type genOptions struct {
	Package    string
	PanelType  string
	BlockName  string
	Schema     string // config component name, for the header
	KbapiType  string
	Strategy   string
	BlockDescr string
}

// objType is one generated model struct.
type objType struct {
	Name  string
	Attrs []*attribute
	Union *union
	child map[string]string // attribute name -> Go type of its object (or list element)
}

type emitter struct {
	o       genOptions
	types   []*objType
	imports map[string]bool
	errs    unsupported
}

func generate(o genOptions, root []*attribute) ([]byte, error) {
	e := &emitter{o: o, imports: map[string]bool{}}
	e.collect("", root, nil)
	var body strings.Builder
	e.emitModels(&body)
	e.emitSchema(&body, root)
	e.emitConversion(&body)
	if len(e.errs) > 0 {
		return nil, fmt.Errorf("unsupported:\n  %s", strings.Join(e.errs, "\n  "))
	}

	var out strings.Builder
	fmt.Fprintf(&out, "// Code generated by scripts/dashboard-codegen-spike from %s (strategy %q). DO NOT EDIT.\n\n", o.Schema, o.Strategy)
	fmt.Fprintf(&out, "// Package %s is the spike's generated Terraform schema, model and conversion for the %s panel.\n", o.Package, o.PanelType)
	fmt.Fprintf(&out, "package %s\n\nimport (\n", o.Package)
	imports := make([]string, 0, len(e.imports))
	for k := range e.imports {
		imports = append(imports, k)
	}
	sort.Strings(imports)
	for _, k := range imports {
		fmt.Fprintf(&out, "\t%q\n", k)
	}
	out.WriteString(")\n\n")
	out.WriteString(body.String())
	src, err := format.Source([]byte(out.String()))
	if err != nil {
		return nil, fmt.Errorf("gofmt generated code: %w\n%s", err, out.String())
	}
	return src, nil
}

func (e *emitter) use(pkg string) { e.imports[pkg] = true }

func (e *emitter) collect(prefix string, attrs []*attribute, u *union) string {
	t := &objType{Name: prefix + "Model", Attrs: attrs, Union: u, child: map[string]string{}}
	e.types = append(e.types, t)
	for _, a := range attrs {
		if a.Kind == kindObject || a.Kind == kindList {
			t.child[a.Name] = e.collect(prefix+goName(a.Name), a.Attributes, a.Union)
		}
	}
	return t.Name
}

func (e *emitter) emitModels(w *strings.Builder) {
	e.use("github.com/hashicorp/terraform-plugin-framework/types")
	for _, t := range e.types {
		if t.Name == "Model" {
			fmt.Fprintf(w, "// Model is the Terraform model of %s.\n", e.o.BlockName)
		} else {
			fmt.Fprintf(w, "// %s is a nested object of %s.\n", t.Name, e.o.BlockName)
		}
		fmt.Fprintf(w, "type %s struct {\n", t.Name)
		for _, a := range t.Attrs {
			var gt string
			switch a.Kind {
			case kindString:
				gt = "types.String"
			case kindBool:
				gt = "types.Bool"
			case kindInt64:
				gt = "types.Int64"
			case kindFloat64:
				gt = "types.Float64"
			case kindObject:
				gt = "*" + t.child[a.Name]
			case kindList:
				gt = "[]" + t.child[a.Name]
			}
			fmt.Fprintf(w, "\t%s %s `tfsdk:%q`\n", goName(a.Name), gt, a.Name)
		}
		w.WriteString("}\n\n")
	}
}

func (e *emitter) emitSchema(w *strings.Builder, root []*attribute) {
	e.use("github.com/hashicorp/terraform-plugin-framework/resource/schema")
	e.use("github.com/elastic/terraform-provider-elasticstack/internal/kibana/dashboard/panelkit")
	fmt.Fprintf(w, "// PanelType is the API discriminator of this panel.\nconst PanelType = %q\n\n", e.o.PanelType)
	fmt.Fprintf(w, "// BlockName is the panel's typed config attribute.\nconst BlockName = %q\n\n", e.o.BlockName)
	w.WriteString("// SchemaAttribute returns the panel's config attribute. The block scaffolding (sibling\n")
	w.WriteString("// exclusion, panel-type guard) stays hand-written in panelkit.\n")
	w.WriteString("func SchemaAttribute() schema.Attribute {\n")
	fmt.Fprintf(w, "\treturn panelkit.PanelConfigBlock(panelkit.PanelConfigBlockOpts{\n\t\tDescription: %q,\n", e.o.BlockDescr)
	w.WriteString("\t\tBlockName: BlockName,\n\t\tPanelType: PanelType,\n\t\tAttributes: Attributes(),\n\t})\n}\n\n")
	w.WriteString("// Attributes returns the config block's attributes.\n")
	w.WriteString("func Attributes() map[string]schema.Attribute {\n\treturn ")
	e.attrMap(w, "", root)
	w.WriteString("\n}\n\n")
}

func (e *emitter) attrMap(w *strings.Builder, path string, attrs []*attribute) {
	w.WriteString("map[string]schema.Attribute{\n")
	for _, a := range attrs {
		fmt.Fprintf(w, "%q: ", a.Name)
		e.attr(w, path+"."+a.Name, a)
		w.WriteString(",\n")
	}
	w.WriteString("}")
}

func (e *emitter) attr(w *strings.Builder, path string, a *attribute) {
	typeName := map[string]string{
		kindString: "StringAttribute", kindBool: "BoolAttribute", kindInt64: "Int64Attribute",
		kindFloat64: "Float64Attribute", kindObject: "SingleNestedAttribute", kindList: "ListNestedAttribute",
	}[a.Kind]
	fmt.Fprintf(w, "schema.%s{\n", typeName)
	if a.Description != "" {
		fmt.Fprintf(w, "MarkdownDescription: %q,\n", a.Description)
	}
	switch {
	case a.Mode == modeRequired:
		w.WriteString("Required: true,\n")
	case a.Mode == modeDefault && e.o.Strategy == strategyComputed:
		w.WriteString("Optional: true,\nComputed: true,\n")
		if d := e.defaultExpr(path, a); d != "" {
			fmt.Fprintf(w, "Default: %s,\n", d)
		}
	default:
		w.WriteString("Optional: true,\n")
	}
	if v := e.validators(a); v != "" {
		w.WriteString(v)
	}
	switch a.Kind {
	case kindObject:
		w.WriteString("Attributes: ")
		e.attrMap(w, path, a.Attributes)
		w.WriteString(",\n")
	case kindList:
		w.WriteString("NestedObject: schema.NestedAttributeObject{\nAttributes: ")
		e.attrMap(w, path+"[]", a.Attributes)
		w.WriteString(",\n},\n")
	}
	w.WriteString("}")
}

func (e *emitter) defaultExpr(path string, a *attribute) string {
	const base = "github.com/hashicorp/terraform-plugin-framework/resource/schema/"
	switch v := a.Default.(type) {
	case string:
		if a.Kind == kindString {
			e.use(base + "stringdefault")
			return fmt.Sprintf("stringdefault.StaticString(%q)", v)
		}
	case bool:
		if a.Kind == kindBool {
			e.use(base + "booldefault")
			return fmt.Sprintf("booldefault.StaticBool(%t)", v)
		}
	case int:
		if a.Kind == kindInt64 {
			e.use(base + "int64default")
			return fmt.Sprintf("int64default.StaticInt64(%d)", v)
		}
	case float64:
		switch a.Kind {
		case kindInt64:
			e.use(base + "int64default")
			return fmt.Sprintf("int64default.StaticInt64(%d)", int64(v))
		case kindFloat64:
			e.use(base + "float64default")
			return fmt.Sprintf("float64default.StaticFloat64(%v)", v)
		}
	}
	e.errs.add(path, fmt.Sprintf("default %v on a %s", a.Default, a.Kind))
	return ""
}

func (e *emitter) validators(a *attribute) string {
	const fwv = "github.com/hashicorp/terraform-plugin-framework-validators/"
	var vs []string
	var vtype string
	switch a.Kind {
	case kindString:
		vtype = "validator.String"
		if a.MinLength != nil {
			e.use(fwv + "stringvalidator")
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthAtLeast(%d)", *a.MinLength))
		}
		if a.MaxLength != nil {
			e.use(fwv + "stringvalidator")
			vs = append(vs, fmt.Sprintf("stringvalidator.LengthAtMost(%d)", *a.MaxLength))
		}
		if len(a.Enum) > 0 {
			e.use(fwv + "stringvalidator")
			q := make([]string, len(a.Enum))
			for i, s := range a.Enum {
				q[i] = fmt.Sprintf("%q", s)
			}
			vs = append(vs, fmt.Sprintf("stringvalidator.OneOf(%s)", strings.Join(q, ", ")))
		}
	case kindList:
		vtype = "validator.List"
		if a.MinItems != nil {
			e.use(fwv + "listvalidator")
			vs = append(vs, fmt.Sprintf("listvalidator.SizeAtLeast(%d)", *a.MinItems))
		}
		if a.MaxItems != nil {
			e.use(fwv + "listvalidator")
			vs = append(vs, fmt.Sprintf("listvalidator.SizeAtMost(%d)", *a.MaxItems))
		}
	}
	if len(vs) == 0 {
		return ""
	}
	e.use("github.com/hashicorp/terraform-plugin-framework/schema/validator")
	return fmt.Sprintf("Validators: []%s{\n%s,\n},\n", vtype, strings.Join(vs, ",\n"))
}

func (e *emitter) emitConversion(w *strings.Builder) {
	e.use("github.com/elastic/terraform-provider-elasticstack/generated/kbapi")
	e.use("github.com/elastic/terraform-provider-elasticstack/scripts/dashboard-codegen-spike/codegenrt")
	e.use("github.com/hashicorp/terraform-plugin-framework/diag")
	k := "kbapi." + e.o.KbapiType
	fmt.Fprintf(w, "// ToAPI converts the Terraform model into the API's config object.\n")
	fmt.Fprintf(w, "func ToAPI(m Model) (%s, diag.Diagnostics) {\n\tvar out %s\n\tdiags := codegenrt.Remarshal(toMapModel(m), &out)\n\treturn out, diags\n}\n\n", k, k)
	if e.o.Strategy == strategyPreserve {
		w.WriteString("// FromAPI converts the API's config object into the Terraform model. prior is the prior plan or\n")
		w.WriteString("// state of this block, or nil on import; it is consulted only for fields with a server default.\n")
		fmt.Fprintf(w, "func FromAPI(api %s, prior *Model) (Model, diag.Diagnostics) {\n", k)
		w.WriteString("\tvar o map[string]any\n\tif diags := codegenrt.Remarshal(api, &o); diags.HasError() {\n\t\treturn Model{}, diags\n\t}\n\treturn fromMapModel(o, prior), nil\n}\n\n")
	} else {
		w.WriteString("// FromAPI converts the API's config object into the Terraform model. It needs no prior state.\n")
		fmt.Fprintf(w, "func FromAPI(api %s) (Model, diag.Diagnostics) {\n", k)
		w.WriteString("\tvar o map[string]any\n\tif diags := codegenrt.Remarshal(api, &o); diags.HasError() {\n\t\treturn Model{}, diags\n\t}\n\treturn fromMapModel(o), nil\n}\n\n")
	}
	for _, t := range e.types {
		e.emitToMap(w, t)
		e.emitFromMap(w, t)
	}
}

func (e *emitter) emitToMap(w *strings.Builder, t *objType) {
	fmt.Fprintf(w, "func toMap%s(m %s) map[string]any {\n", t.Name, t.Name)
	if t.Union != nil {
		w.WriteString("\tswitch {\n")
		for _, v := range t.Union.Variants {
			fmt.Fprintf(w, "\tcase m.%s != nil:\n\t\tout := toMap%s(*m.%s)\n\t\tout[%q] = %q\n\t\treturn out\n",
				goName(v.Key), t.child[v.Key], goName(v.Key), t.Union.Discriminator, v.Value)
		}
		w.WriteString("\t}\n\treturn map[string]any{}\n}\n\n")
		return
	}
	w.WriteString("\tout := map[string]any{}\n")
	for _, a := range t.Attrs {
		f := goName(a.Name)
		switch a.Kind {
		case kindString, kindBool, kindInt64, kindFloat64:
			fmt.Fprintf(w, "\tcodegenrt.Put%s(out, %q, m.%s)\n", runtimeKind(a.Kind), a.Name, f)
		case kindObject:
			fmt.Fprintf(w, "\tif m.%s != nil {\n\t\tout[%q] = toMap%s(*m.%s)\n\t}\n", f, a.Name, t.child[a.Name], f)
		case kindList:
			fmt.Fprintf(w, "\tif m.%s != nil {\n\t\titems := make([]any, 0, len(m.%s))\n\t\tfor _, it := range m.%s {\n\t\t\titems = append(items, toMap%s(it))\n\t\t}\n\t\tout[%q] = items\n\t}\n",
				f, f, f, t.child[a.Name], a.Name)
		}
	}
	w.WriteString("\treturn out\n}\n\n")
}

func (e *emitter) emitFromMap(w *strings.Builder, t *objType) {
	preserve := e.o.Strategy == strategyPreserve
	if preserve {
		fmt.Fprintf(w, "func fromMap%s(o map[string]any, prior *%s) %s {\n\tvar m %s\n\tvar p %s\n\tif prior != nil {\n\t\tp = *prior\n\t}\n", t.Name, t.Name, t.Name, t.Name, t.Name)
	} else {
		fmt.Fprintf(w, "func fromMap%s(o map[string]any) %s {\n\tvar m %s\n", t.Name, t.Name, t.Name)
	}
	priorArg := func(field string) string {
		if preserve {
			return ", p." + field
		}
		return ""
	}
	if t.Union != nil {
		fmt.Fprintf(w, "\tswitch o[%q] {\n", t.Union.Discriminator)
		for _, v := range t.Union.Variants {
			f := goName(v.Key)
			fmt.Fprintf(w, "\tcase %q:\n\t\tv := fromMap%s(o%s)\n\t\tm.%s = &v\n", v.Value, t.child[v.Key], priorArg(f), f)
		}
		w.WriteString("\t}\n\treturn m\n}\n\n")
		return
	}
	for _, a := range t.Attrs {
		f := goName(a.Name)
		switch a.Kind {
		case kindString, kindBool, kindInt64, kindFloat64:
			read := fmt.Sprintf("codegenrt.%s(o, %q)", runtimeKind(a.Kind), a.Name)
			if preserve && a.Mode == modeDefault {
				read = fmt.Sprintf("codegenrt.Defaulted%s(%s, p.%s, %s)", runtimeKind(a.Kind), read, f, goLiteral(a.Default))
			}
			fmt.Fprintf(w, "\tm.%s = %s\n", f, read)
		case kindObject:
			fmt.Fprintf(w, "\tif v, ok := codegenrt.Object(o, %q); ok {\n\t\tx := fromMap%s(v%s)\n\t\tm.%s = &x\n\t}\n", a.Name, t.child[a.Name], priorArg(f), f)
		case kindList:
			loopVar := "_"
			if preserve {
				loopVar = "i"
			}
			fmt.Fprintf(w, "\tif vs, ok := codegenrt.List(o, %q); ok {\n\t\tm.%s = make([]%s, 0, len(vs))\n\t\tfor %s, v := range vs {\n", a.Name, f, t.child[a.Name], loopVar)
			w.WriteString("\t\t\tov, ok := v.(map[string]any)\n\t\t\tif !ok {\n\t\t\t\tcontinue\n\t\t\t}\n")
			if preserve {
				fmt.Fprintf(w, "\t\t\tvar pi *%s\n\t\t\tif i < len(p.%s) {\n\t\t\t\tpi = &p.%s[i]\n\t\t\t}\n", t.child[a.Name], f, f)
				fmt.Fprintf(w, "\t\t\tm.%s = append(m.%s, fromMap%s(ov, pi))\n", f, f, t.child[a.Name])
			} else {
				fmt.Fprintf(w, "\t\t\tm.%s = append(m.%s, fromMap%s(ov))\n", f, f, t.child[a.Name])
			}
			w.WriteString("\t\t}\n\t}\n")
		}
	}
	w.WriteString("\treturn m\n}\n\n")
}

func runtimeKind(kind string) string {
	return map[string]string{kindString: "String", kindBool: "Bool", kindInt64: "Int64", kindFloat64: "Float64"}[kind]
}

func goLiteral(v any) string {
	if s, ok := v.(string); ok {
		return fmt.Sprintf("%q", s)
	}
	return fmt.Sprint(v)
}

// initialisms Go spells in capitals.
var initialisms = map[string]string{"id": "ID", "url": "URL", "json": "JSON", "api": "API", "http": "HTTP", "ui": "UI", "esql": "ESQL"}

func goName(s string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == '.' }) {
		if up, ok := initialisms[part]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}

// kbapiTypeName is oapi-codegen's Go name for a component schema.
func kbapiTypeName(component string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(component, func(r rune) bool { return r == '_' || r == '-' }) {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
